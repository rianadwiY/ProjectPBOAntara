    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        // Validasi
    if (model.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this, "Belum ada barang yang dipilih!");
        return;
    }

    if (txtBayar.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Masukkan jumlah pembayaran!");
        return;
    }

    try {
        // Untuk sementara gunakan ID Kasir = 1
        int idKasir = 1;

        double total = Double.parseDouble(txtTotal.getText());
        double bayar = Double.parseDouble(txtBayar.getText());
        double kembalian = Double.parseDouble(txtKembalian.getText());

        if (bayar < total) {
            JOptionPane.showMessageDialog(this, "Jumlah bayar kurang dari total!");
            return;
        }

        // Simpan transaksi
        int idTransaksi = transaksiController.simpanTransaksi(
                idKasir,
                total,
                bayar,
                kembalian
        );

        // Simpan detail transaksi
        for (int i = 0; i < model.getRowCount(); i++) {

            int idBarang = Integer.parseInt(model.getValueAt(i, 1).toString());   // kolom ID Barang 
            double harga = Double.parseDouble(model.getValueAt(i, 4).toString()); // kolom Harga
            int qty = Integer.parseInt(model.getValueAt(i, 5).toString());        // kolom Qty
            double subtotal = Double.parseDouble(model.getValueAt(i, 6).toString()); // kolom Subtotal

            transaksiController.simpanDetail(
                    idTransaksi,
                    idBarang,
                    qty,
                    harga,
                    subtotal
            );

            transaksiController.updateStok(idBarang, qty);
        }

        bgm.playBGM("bgm.mp3"); // Memanggil file audionya

        JOptionPane.showMessageDialog(this, "Transaksi berhasil disimpan!");

        bgm.stopBGM(); // Matikan musik
        new DashboardForm().setVisible(true); // Buka kembali Dashboard
        this.dispose(); // Tutup form Transaksi ini

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Data barang atau nominal tidak valid: " + e.getMessage());
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal menyimpan transaksi: " + e.getMessage());
        e.printStackTrace();
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

