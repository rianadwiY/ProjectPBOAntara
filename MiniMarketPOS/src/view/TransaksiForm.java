    private void btnCariActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCariActionPerformed
        String kode = txtKodeBarang.getText();

    Barang barang = barangController.cariBarangByKode(kode);

    if (barang != null) {

        barangDipilih = barang;

        lblNamaBarang.setText(barang.getNamaBarang());
        lblHarga.setText(String.valueOf(barang.getHarga()));

    } else {

        barangDipilih = null;
        JOptionPane.showMessageDialog(this, "Barang tidak ditemukan!");

    }
    }//GEN-LAST:event_btnCariActionPerformed

    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        if (barangDipilih == null) {
        JOptionPane.showMessageDialog(this, "Cari barang terlebih dahulu!");
        return;
    }

    double harga = Double.parseDouble(lblHarga.getText());
    int qty = Integer.parseInt(txtJumlah.getText());

    if (qty <= 0) {
        JOptionPane.showMessageDialog(this, "Jumlah harus lebih dari 0!");
        return;
    }

    if (qty > barangDipilih.getStok()) {
        JOptionPane.showMessageDialog(this,
            "Stok tidak cukup! Stok tersedia: " + barangDipilih.getStok());
        return;
    }

    double subtotal = harga * qty;

    model.addRow(new Object[]{
        model.getRowCount() + 1,
        barangDipilih.getIdBarang(), 
        barangDipilih.getKodeBarang(),
        lblNamaBarang.getText(),
        harga,
        qty,
        subtotal
    });

    hitungTotal();
    }//GEN-LAST:event_btnTambahActionPerformed

