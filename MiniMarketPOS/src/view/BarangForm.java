    private void tblBarangMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblBarangMouseClicked
        // TODO add your handling code here:
       int baris = tblBarang.getSelectedRow();

    if (baris >= 0) {

        // Isi ID Barang
        txtIdBarang.setText(
            model.getValueAt(baris, 0).toString()
        );

        // Isi Kode Barang
        txtkdBarang.setText(
            model.getValueAt(baris, 1).toString()
        );

        // Isi Nama Barang
        txtNamaBarang.setText(
            model.getValueAt(baris, 2).toString()
        );

        // Isi Kategori melalui ComboBox
        cmbKategori.setSelectedItem(
            model.getValueAt(baris, 3).toString()
        );

        // Isi Harga
        txtHarga.setText(
            model.getValueAt(baris, 4).toString()
        );

        // Isi Stok
        txtStok.setText(
            model.getValueAt(baris, 5).toString()
        );

        // Simpan data awal sebelum diedit
        dataAwalNama =
            txtNamaBarang.getText();

        dataAwalKategori =
            cmbKategori.getSelectedItem().toString();

        dataAwalHarga =
            txtHarga.getText();

        dataAwalStok =
            txtStok.getText();
    }
    }//GEN-LAST:event_tblBarangMouseClicked

