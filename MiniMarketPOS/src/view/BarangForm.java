    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // Validasi Nama Barang
    if (txtNamaBarang.getText().isEmpty() ||
        txtHarga.getText().isEmpty() ||
        txtStok.getText().isEmpty()) {

        JOptionPane.showMessageDialog(
            this,
            "Semua data harus diisi!",
            "Peringatan",
            JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    // Ambil kategori dari ComboBox
    String kategori = cmbKategori.getSelectedItem().toString();

    // Pastikan kategori dipilih
    if (kategori.equals("-- Pilih Kategori --")) {

        JOptionPane.showMessageDialog(
            this,
            "Silakan pilih kategori barang!",
            "Peringatan",
            JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    try {

        Barang barang = new Barang();

        barang.setIdBarang(
            Integer.parseInt(txtIdBarang.getText())
        );

        barang.setKodeBarang(
            txtkdBarang.getText()
        );

        barang.setNamaBarang(
            txtNamaBarang.getText()
        );

        barang.setKategori(
            kategori
        );

        barang.setHarga(
            Double.parseDouble(txtHarga.getText())
        );

        barang.setStok(
            Integer.parseInt(txtStok.getText())
        );

        // Simpan ke database
        controller.tambah(barang);

        // Refresh tabel
        tampilData();

        // Reset form
        kosong();

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
            this,
            "Harga dan Stok harus berupa angka!",
            "Error",
            JOptionPane.ERROR_MESSAGE
        );

    }
        
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        // TODO add your handling code here:
        // Pastikan user sudah memilih data dari JTable
    if (dataAwalNama == null) {

        JOptionPane.showMessageDialog(
            this,
            "Silakan pilih data barang yang ingin diubah dari tabel!",
            "Peringatan",
            JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    // Ambil data terbaru dari form
    String namaBaru = txtNamaBarang.getText();
    String kategoriBaru = cmbKategori.getSelectedItem().toString();
    String hargaBaru = txtHarga.getText();
    String stokBaru = txtStok.getText();

    // Cek apakah ada perubahan
    boolean tidakAdaPerubahan =
            dataAwalNama.equals(namaBaru) &&
            dataAwalKategori.equals(kategoriBaru) &&
            dataAwalHarga.equals(hargaBaru) &&
            dataAwalStok.equals(stokBaru);

    // Jika tidak ada perubahan
    if (tidakAdaPerubahan) {

        JOptionPane.showMessageDialog(
            this,
            "Tidak ada perubahan data!\nSilakan ubah Nama, Kategori, Harga, atau Stok terlebih dahulu.",
            "Peringatan",
            JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    // Validasi input kosong
    if (namaBaru.isEmpty() ||
        kategoriBaru.isEmpty() ||
        hargaBaru.isEmpty() ||
        stokBaru.isEmpty()) {

        JOptionPane.showMessageDialog(
            this,
            "Semua data harus diisi!",
            "Peringatan",
            JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    try {

        Barang barang = new Barang();

        barang.setIdBarang(
            Integer.parseInt(txtIdBarang.getText())
        );

        // Kode barang tetap menggunakan kode yang sudah ada
        barang.setKodeBarang(
            txtkdBarang.getText()
        );

        barang.setNamaBarang(namaBaru);
        barang.setKategori(kategoriBaru);

        barang.setHarga(
            Double.parseDouble(hargaBaru)
        );

        barang.setStok(
            Integer.parseInt(stokBaru)
        );

        // Update data
        controller.ubah(barang);

        // Refresh tabel
        tampilData();

        // Kosongkan form
        kosong();

        // Reset data awal
        dataAwalNama = null;
        dataAwalKategori = null;
        dataAwalHarga = null;
        dataAwalStok = null;

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
            this,
            "Harga dan Stok harus berupa angka!",
            "Error",
            JOptionPane.ERROR_MESSAGE
        );

    }
    }//GEN-LAST:event_btnUbahActionPerformed

