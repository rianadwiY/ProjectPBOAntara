private void tampilData() {

    model.setRowCount(0);

    try {

        ResultSet rs = controller.tampilData();

        while (rs.next()) {

            Object[] row = {

                rs.getInt("id_barang"),
                rs.getString("kode_barang"),
                rs.getString("nama_barang"),
                rs.getString("kategori"),
                rs.getDouble("harga"),
                rs.getInt("stok")

            };

            model.addRow(row);

        }

    } catch (Exception e) {

        System.out.println(e.getMessage());

    }

}
