    private void tampilData(){

    model = (DefaultTableModel) tblKasir.getModel();

    model.setRowCount(0);

    try{

        ResultSet rs = controller.tampilData();

        while(rs.next()){

            Object[] data = {

                rs.getInt("id_kasir"),
                rs.getString("nama"),
                rs.getString("username"),
                rs.getString("password")

            };

            model.addRow(data);

        }

    }catch(Exception e){

        System.out.println(e.getMessage());

    }

}
