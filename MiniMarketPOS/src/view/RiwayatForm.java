private void tampilData() {

    model = (DefaultTableModel) tblRiwayat.getModel();

    model.setRowCount(0);

    try {

        ResultSet rs = controller.tampilRiwayat();

        while (rs.next()) {

            Object[] data = {

                rs.getInt("id_transaksi"),
                rs.getString("tanggal"),
                rs.getString("nama"),
                rs.getDouble("total"),
                rs.getDouble("bayar"),
                rs.getDouble("kembalian")

            };

            model.addRow(data);

        }

    } catch (Exception e) {

        System.out.println(e.getMessage());

    }

}

